// Writes src/diagrams/registry.ts and src/models.ts from the list of implemented diagram types.
// Usage: node scripts/gen-registry.mjs
import { writeFileSync } from 'node:fs';

// [export name in its index.ts, folder, model type, file that declares the model type]
const DIAGRAMS = [
  ['flowchart', 'flowchart', 'FlowchartModel', 'types'],
  ['pie', 'pie', 'PieModel', 'model'],
  ['er', 'er', 'ErModel', 'types'],
  ['mindmap', 'mindmap', 'MindmapModel', 'db'],
  ['kanban', 'kanban', 'KanbanModel', 'db'],
  ['timeline', 'timeline', 'TimelineModel', 'db'],
  ['journey', 'journey', 'JourneyModel', 'db'],
  ['classDiagram', 'class', 'ClassModel', 'types'],
  ['quadrantChart', 'quadrant', 'QuadrantModel', 'db'],
  ['xychart', 'xychart', 'XyChartModel', 'db'],
  ['state', 'state', 'StateModel', 'types'],
  ['gantt', 'gantt', 'GanttModel', 'types'],
  ['architecture', 'architecture', 'ArchitectureModel', 'db'],
  ['requirement', 'requirement', 'RequirementModel', 'types'],
  ['sankey', 'sankey', 'SankeyModel', 'db'],
  ['packet', 'packet', 'PacketModel', 'model'],
  ['radar', 'radar', 'RadarModel', 'model'],
  ['treemap', 'treemap', 'TreemapModel', 'model'],
  ['info', 'info', 'InfoModel', 'model'],
  ['sequence', 'sequence', 'SequenceModel', 'types'],
  ['gitGraph', 'git', 'GitModel', 'db'],
  ['c4', 'c4', 'C4Model', 'types'],
  ['block', 'block', 'BlockModel', 'types'],
];

const imports = DIAGRAMS.map(([name, folder]) => `import { ${name} } from './${folder}/index.js';`).sort();
writeFileSync(
  'src/diagrams/registry.ts',
  `import type { DiagramType } from '../detect.js';
import type { Diagram } from '../types.js';
${imports.join('\n')}

// Every implemented diagram type. Detection covers more types than this; the rest are unsupported.
// Generated by scripts/gen-registry.mjs.
const all = [
${DIAGRAMS.map(([name]) => `  ${name},`).join('\n')}
] as Diagram<unknown>[];

export const diagrams = new Map<DiagramType, Diagram<unknown>>(all.map((d) => [d.type, d]));
`
);

const models = DIAGRAMS.map(([, folder, model, file]) => `import type { ${model} } from './diagrams/${folder}/${file}.js';`).sort();
writeFileSync(
  'src/models.ts',
  `// Generated by scripts/gen-registry.mjs.
${models.join('\n')}

export type {
${DIAGRAMS.map(([, , model]) => `  ${model},`).join('\n')}
};

// The union of every implemented diagram's model; narrow it with its \`type\` field.
export type DiagramModel =
${DIAGRAMS.map(([, , model]) => `  | ${model}`).join('\n')};
`
);
